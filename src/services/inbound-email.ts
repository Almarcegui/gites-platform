// ---------------------------------------------------------------------------
// Parsing MIME
// ---------------------------------------------------------------------------

export interface ParsedEmail {
  messageId: string | null;
  from: string;
  fromName: string | null;
  to: string | null;
  subject: string;
  textBody: string;
  isAutoGenerated: boolean;
}

function unfoldHeaders(rawHeaders: string): Map<string, string> {
  const map = new Map<string, string>();
  const lines = rawHeaders.split(/\r?\n/);
  let current = "";
  const flush = () => {
    if (!current) return;
    const idx = current.indexOf(":");
    if (idx > 0) {
      const name = current.slice(0, idx).trim().toLowerCase();
      const value = current.slice(idx + 1).trim();
      if (!map.has(name)) map.set(name, value);
    }
    current = "";
  };
  for (const line of lines) {
    if (/^[ \t]/.test(line)) {
      current += " " + line.trim();
    } else {
      flush();
      current = line;
    }
  }
  flush();
  return map;
}

/** Décode les encoded-words RFC 2047 : =?utf-8?B?…?= / =?iso-8859-1?Q?…?= */
export function decodeEncodedWords(value: string): string {
  return value.replace(/=\?([^?]+)\?([bBqQ])\?([^?]*)\?=/g, (_m, charset: string, enc: string, text: string) => {
    try {
      const bytes =
        enc.toUpperCase() === "B"
          ? base64ToBytes(text)
          : qpToBytes(text.replace(/_/g, " "), true);
      return decodeBytes(bytes, charset);
    } catch {
      return text;
    }
  });
}

function base64ToBytes(b64: string): Uint8Array {
  const clean = b64.replace(/[^A-Za-z0-9+/=]/g, "");
  const bin = atob(clean);
  const out = new Uint8Array(bin.length);
  for (let i = 0; i < bin.length; i++) out[i] = bin.charCodeAt(i);
  return out;
}

function qpToBytes(text: string, header = false): Uint8Array {
  // quoted-printable : =XX, soft line breaks =\r?\n
  const src = header ? text : text.replace(/=\r?\n/g, "");
  const out: number[] = [];
  for (let i = 0; i < src.length; i++) {
    const c = src[i]!;
    if (c === "=" && /^[0-9A-Fa-f]{2}$/.test(src.slice(i + 1, i + 3))) {
      out.push(parseInt(src.slice(i + 1, i + 3), 16));
      i += 2;
    } else {
      out.push(c.charCodeAt(0) & 0xff);
    }
  }
  return new Uint8Array(out);
}

function decodeBytes(bytes: Uint8Array, charset: string): string {
  const cs = charset.trim().toLowerCase();
  try {
    return new TextDecoder(cs === "us-ascii" ? "utf-8" : cs).decode(bytes);
  } catch {
    return new TextDecoder("utf-8").decode(bytes);
  }
}

function headerParam(headerValue: string, param: string): string | null {
  const m = new RegExp(`${param}\\s*=\\s*"?([^";]+)"?`, "i").exec(headerValue);
  return m ? m[1]!.trim() : null;
}

interface MimePart {
  headers: Map<string, string>;
  body: string;
}

function splitParts(body: string, boundary: string): MimePart[] {
  const parts: MimePart[] = [];
  const chunks = body.split(new RegExp(`--${boundary.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")}(?:--)?\r?\n?`));
  for (const chunk of chunks) {
    const sep = chunk.search(/\r?\n\r?\n/);
    if (sep < 0) continue;
    const headers = unfoldHeaders(chunk.slice(0, sep));
    if (headers.size === 0) continue;
    parts.push({ headers, body: chunk.slice(sep).replace(/^\r?\n\r?\n/, "") });
  }
  return parts;
}

function decodeBody(body: string, headers: Map<string, string>): string {
  const cte = (headers.get("content-transfer-encoding") ?? "").toLowerCase();
  const charset = headerParam(headers.get("content-type") ?? "", "charset") ?? "utf-8";
  if (cte === "base64") return decodeBytes(base64ToBytes(body), charset);
  if (cte === "quoted-printable") return decodeBytes(qpToBytes(body), charset);
  return body;
}

/** Extrait le meilleur text/plain d'un corps (multipart à 2 niveaux max). */
function extractText(body: string, headers: Map<string, string>, depth = 0): string {
  const contentType = (headers.get("content-type") ?? "text/plain").toLowerCase();
  if (contentType.startsWith("multipart/") && depth < 3) {
    const boundary = headerParam(headers.get("content-type") ?? "", "boundary");
    if (boundary) {
      const parts = splitParts(body, boundary);
      const plain = parts.find((p) => (p.headers.get("content-type") ?? "").toLowerCase().startsWith("text/plain"));
      if (plain) return decodeBody(plain.body, plain.headers).trim();
      for (const p of parts) {
        const ct = (p.headers.get("content-type") ?? "").toLowerCase();
        if (ct.startsWith("multipart/")) {
          const nested = extractText(p.body, p.headers, depth + 1);
          if (nested) return nested;
        }
      }
      const htmlPart = parts.find((p) => (p.headers.get("content-type") ?? "").toLowerCase().startsWith("text/html"));
      if (htmlPart) return htmlToText(decodeBody(htmlPart.body, htmlPart.headers));
      return "";
    }
  }
  if (contentType.startsWith("text/html")) return htmlToText(decodeBody(body, headers));
  return decodeBody(body, headers).trim();
}

function htmlToText(html: string): string {
  return html
    .replace(/<style[\s\S]*?<\/style>/gi, " ")
    .replace(/<script[\s\S]*?<\/script>/gi, " ")
    .replace(/<br\s*\/?>/gi, "\n")
    .replace(/<\/p>/gi, "\n\n")
    .replace(/<[^>]+>/g, "")
    .replace(/&nbsp;/g, " ")
    .replace(/&amp;/g, "&")
    .replace(/&lt;/g, "<")
    .replace(/&gt;/g, ">")
    .replace(/\n{3,}/g, "\n\n")
    .trim();
}

function parseAddress(value: string): { email: string; name: string | null } {
  const decoded = decodeEncodedWords(value);
  const angle = /<([^>]+)>/.exec(decoded);
  if (angle) {
    const name = decoded.slice(0, angle.index).replace(/["']/g, "").trim();
    return { email: angle[1]!.trim().toLowerCase(), name: name || null };
  }
  return { email: decoded.trim().toLowerCase(), name: null };
}

export function parseRawEmail(raw: string): ParsedEmail {
  const sep = raw.search(/\r?\n\r?\n/);
  const headerBlock = sep >= 0 ? raw.slice(0, sep) : raw;
  const body = sep >= 0 ? raw.slice(sep).replace(/^\r?\n\r?\n/, "") : "";
  const headers = unfoldHeaders(headerBlock);

  const fromRaw = headers.get("from") ?? "";
  const { email: from, name: fromName } = parseAddress(fromRaw);
  const to = headers.get("to") ? parseAddress(headers.get("to")!).email : null;

  const autoSubmitted = (headers.get("auto-submitted") ?? "no").toLowerCase();
  const precedence = (headers.get("precedence") ?? "").toLowerCase();
  const isAutoGenerated =
    (autoSubmitted !== "" && autoSubmitted !== "no") ||
    ["bulk", "junk", "list", "auto_reply"].includes(precedence) ||
    headers.has("x-auto-response-suppress") ||
    headers.has("list-id");

  return {
    messageId: headers.get("message-id")?.trim() || null,
    from,
    fromName,
    to,
    subject: decodeEncodedWords(headers.get("subject") ?? "").trim(),
    textBody: extractText(body, headers).slice(0, 20000),
    isAutoGenerated,
  };
}

