// Tests de l'intégration email : parseur MIME minimal (multipart, encodages,
// encoded-words) et traitement complet sur vraie D1 (rattachement résa,
// accusé automatique avec anti-boucle, dédoublonnage par Message-ID).
import { afterAll, beforeAll, beforeEach, describe, expect, it } from "vitest";
import type { D1Database } from "@cloudflare/workers-types";
import { createTestDb, type TestDb } from "./helpers/d1";
import { buildReplyMime, decodeEncodedWords, parseRawEmail, processInboundEmail } from "../src/services/inbound-email";
import { createBookingAtomic, getSettings, listMessages, updateSettings, upsertGuest } from "../src/db/repo";

let t: TestDb;
let db: D1Database;
const ENV = { PUBLIC_BASE_URL: "http://test.local" } as Env;
const NOW = new Date("2026-07-12T10:00:00Z");

beforeAll(async () => {
  t = await createTestDb();
  db = t.db;
});
afterAll(async () => {
  await t.dispose();
});
beforeEach(async () => {
  for (const table of ["messages", "payments", "email_log", "audit_log", "bookings", "guests"]) {
    await db.prepare(`DELETE FROM ${table}`).run();
  }
  await updateSettings(db, 1, { auto_reply_enabled: "false", email_forward_to: "" });
});

// --- fixtures MIME -----------------------------------------------------------

const SIMPLE = [
  "From: Jean Dupont <jean@example.com>",
  "To: reservation@lesgitesdupremore.be",
  "Subject: Question sejour",
  "Message-ID: <abc123@mail.example.com>",
  "Content-Type: text/plain; charset=utf-8",
  "",
  "Bonjour, le sauna est-il disponible en octobre ?",
].join("\r\n");

const MULTIPART_QP = [
  "From: =?utf-8?B?TcOpbGFuaWUgRHVwcsOp?= <melanie@example.com>",
  "To: reservation@lesgitesdupremore.be",
  "Subject: =?utf-8?Q?R=C3=A9servation_PM-2026-001_=E2=80=94_arriv=C3=A9e?=",
  "Message-ID: <multi-1@mail>",
  'Content-Type: multipart/alternative; boundary="BOUND42"',
  "",
  "--BOUND42",
  "Content-Type: text/plain; charset=utf-8",
  "Content-Transfer-Encoding: quoted-printable",
  "",
  "Bonjour, nous arriverons vers 18h. =C3=80 bient=C3=B4t !",
  "--BOUND42",
  "Content-Type: text/html; charset=utf-8",
  "",
  "<p>Bonjour, nous arriverons vers 18h.</p>",
  "--BOUND42--",
  "",
].join("\r\n");

const AUTO_REPLY_MAIL = [
  "From: noreply@booking-robot.com",
  "To: reservation@lesgitesdupremore.be",
  "Subject: Out of office",
  "Auto-Submitted: auto-replied",
  "Message-ID: <robot-1@mail>",
  "",
  "Je suis absent.",
].join("\r\n");

describe("parseRawEmail", () => {
  it("mail simple : from, sujet, corps, message-id", () => {
    const p = parseRawEmail(SIMPLE);
    expect(p.from).toBe("jean@example.com");
    expect(p.fromName).toBe("Jean Dupont");
    expect(p.to).toBe("reservation@lesgitesdupremore.be");
    expect(p.subject).toBe("Question sejour");
    expect(p.textBody).toContain("sauna");
    expect(p.messageId).toBe("<abc123@mail.example.com>");
    expect(p.isAutoGenerated).toBe(false);
  });

  it("multipart + quoted-printable + encoded-words (accents)", () => {
    const p = parseRawEmail(MULTIPART_QP);
    expect(p.fromName).toBe("Mélanie Dupré");
    expect(p.subject).toBe("Réservation PM-2026-001 — arrivée");
    expect(p.textBody).toBe("Bonjour, nous arriverons vers 18h. À bientôt !");
  });

  it("détecte les mails automatiques (anti-boucle)", () => {
    expect(parseRawEmail(AUTO_REPLY_MAIL).isAutoGenerated).toBe(true);
    expect(parseRawEmail(SIMPLE).isAutoGenerated).toBe(false);
  });

  it("décode les encoded-words isolés", () => {
    expect(decodeEncodedWords("=?iso-8859-1?Q?d=E9p=F4t?=")).toBe("dépôt");
  });

  it("retombe sur le HTML converti quand il n'y a pas de text/plain", () => {
    const htmlOnly = [
      "From: a@b.c", "Subject: x", "Content-Type: text/html; charset=utf-8", "",
      "<html><body><p>Ligne 1</p><p>Ligne &amp; 2</p></body></html>",
    ].join("\r\n");
    const p = parseRawEmail(htmlOnly);
    expect(p.textBody).toContain("Ligne 1");
    expect(p.textBody).toContain("Ligne & 2");
  });
});

describe("buildReplyMime", () => {
  it("produit un MIME re-parsable avec sujet accentué et In-Reply-To", () => {
    const mime = buildReplyMime("resa@gites.be", "client@x.be", "Re: Réservation reçue", "Merci — à bientôt !", "<orig@id>");
    expect(mime).toContain("In-Reply-To: <orig@id>");
    expect(mime).toContain("Auto-Submitted: auto-replied");
    const parsed = parseRawEmail(mime);
    expect(parsed.subject).toBe("Re: Réservation reçue");
    expect(parsed.textBody).toBe("Merci — à bientôt !");
    expect(parsed.isAutoGenerated).toBe(true); // notre propre accusé ne déclencherait pas de boucle
  });
});

describe("processInboundEmail (D1)", () => {
  it("stocke, rattache par référence dans le sujet, et dédoublonne par Message-ID", async () => {
    const guestId = await upsertGuest(db, { email: "jean@example.com", lastName: "Dupont" });
    const created = await createBookingAtomic(db, {
      unitId: 2, checkin: "2026-10-10", checkout: "2026-10-12", adults: 4, children: 0,
      status: "confirmed", source: "manual", guestId, now: NOW,
    });
    expect(created.ok).toBe(true);
    const ref = created.ok ? created.reference : "";

    const parsed = parseRawEmail(SIMPLE);
    parsed.subject = `Question sur ${ref}`;
    const r1 = await processInboundEmail(db, ENV, parsed, {}, NOW);
    expect(r1.stored).toBe(true);
    expect(r1.bookingRef).toBe(ref);
    // re-livraison du même Message-ID → ignorée
    const r2 = await processInboundEmail(db, ENV, parsed, {}, NOW);
    expect(r2.duplicate).toBe(true);
    const list = await listMessages(db, {});
    expect(list).toHaveLength(1);
    expect(list[0]?.bookingReference).toBe(ref);
    expect(list[0]?.status).toBe("nouveau");
  });

  it("rattache par email du client quand il n'y a pas de référence", async () => {
    const guestId = await upsertGuest(db, { email: "jean@example.com", lastName: "Dupont" });
    await createBookingAtomic(db, {
      unitId: 1, checkin: "2026-11-05", checkout: "2026-11-08", adults: 6, children: 0,
      status: "confirmed", source: "manual", guestId, now: NOW,
    });
    const r = await processInboundEmail(db, ENV, parseRawEmail(SIMPLE), {}, NOW);
    expect(r.bookingRef).not.toBeNull();
    const list = await listMessages(db, {});
    expect(list[0]?.guestId).toBe(guestId);
  });

  it("accusé de réception : envoyé si activé, jamais à un mail automatique", async () => {
    await updateSettings(db, 1, { auto_reply_enabled: "true" });
    const replies: { subject: string; body: string }[] = [];
    const hooks = { reply: async (subject: string, body: string) => { replies.push({ subject, body }); } };

    await processInboundEmail(db, ENV, parseRawEmail(SIMPLE), hooks, NOW);
    expect(replies).toHaveLength(1);
    expect(replies[0]?.subject).toBe("Re: Question sejour");
    expect(replies[0]?.body).toContain("bien reçu");

    // mail auto-généré → pas de réponse (anti-boucle)
    await processInboundEmail(db, ENV, parseRawEmail(AUTO_REPLY_MAIL), hooks, NOW);
    expect(replies).toHaveLength(1);

    // journalisé dans email_log
    const log = await db.prepare("SELECT kind, status FROM email_log ORDER BY id").all();
    expect((log.results[0] as { kind: string }).kind).toBe("auto_reply");
    const inbox = await listMessages(db, {});
    const jean = inbox.find((e) => e.fromEmail === "jean@example.com");
    expect(jean?.autoReplied).toBe(true);
  });

  it("accusé désactivé par défaut : aucun envoi", async () => {
    const replies: string[] = [];
    await processInboundEmail(db, ENV, parseRawEmail(SIMPLE), { reply: async (s) => { replies.push(s); } }, NOW);
    expect(replies).toHaveLength(0);
    expect((await getSettings(db, 1)).autoReplyEnabled).toBe(false);
  });

  it("transfert vers l'adresse configurée, marqué sur le mail", async () => {
    await updateSettings(db, 1, { email_forward_to: "julien@example.com" });
    const forwards: string[] = [];
    const r = await processInboundEmail(
      db, ENV, parseRawEmail(SIMPLE), { forward: async (to) => { forwards.push(to); } }, NOW,
    );
    expect(forwards).toEqual(["julien@example.com"]);
    expect(r.forwarded).toBe(true);
    const list = await listMessages(db, {});
    expect(list[0]?.forwarded).toBe(true);
  });

  it("résout le domaine par l'adresse de contact (Moulin ≠ Pré Moré)", async () => {
    await db.prepare("UPDATE properties SET contact_email = 'resa@moulindebraives.be' WHERE id = 2").run();
    const parsed = parseRawEmail(SIMPLE);
    parsed.to = "resa@moulindebraives.be";
    parsed.messageId = "<autre@id>";
    const r = await processInboundEmail(db, ENV, parsed, {}, NOW);
    expect(r.propertyId).toBe(2);
  });
});
